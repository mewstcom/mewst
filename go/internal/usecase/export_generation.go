package usecase

import "time"

const (
	// ExportPostPageSizeは生成処理がexportのsnapshotから一度に読み取る
	// 投稿の件数。月全体、ましてexport全体を読むと生成処理が保持するメモリが投稿
	// 件数に比例して増えるため、1ページだけを保持してアーカイブへ流し込む。
	//
	// この件数は、ラウンドトリップを減らす効果が頭打ちになる地点。10万件の
	// snapshotの走査は1ページ100件では約3倍の時間がかかる一方、10倍大きな
	// ページにしてもほとんど短縮されず、メモリに載る投稿だけが10倍になる。
	ExportPostPageSize int32 = 1000

	// GenerateExportTimeoutは生成1回の試行の上限。停止した試行 (固まった
	// アップロード、切れた接続) が、プロセスが生きている限り他プロフィールの
	// エクスポートを塞ぎ続けるのではなく、単一workerのexportキューを解放して
	// staleなstartedとして回復されるようにするための上限。
	//
	// 値は要件が前提とするエクスポート規模の実測コストより十分大きく取る。DBが
	// 遅い場合、オブジェクトストレージへの回線が細い場合、その規模を大きく超える
	// プロフィールのいずれもこの時間内に完了するようにするため。
	GenerateExportTimeout = 15 * time.Minute
)
